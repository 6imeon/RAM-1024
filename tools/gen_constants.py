"""Generate RAM-1024 round constants: consecutive 64-bit words of the binary
expansion of frac(pi), computed in ramhash/_pi.py.

    python3 tools/gen_constants.py > csrc/ram_constants.h
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from ramhash._pi import MAX_ROUNDS, NWORDS, pi_fraction_words  # noqa: E402,F401

if __name__ == "__main__":
    words = pi_fraction_words()
    print("/* Generated by tools/gen_constants.py: frac(pi) in 64-bit words. */")
    print("#define RAM_MAX_ROUNDS %d" % MAX_ROUNDS)
    print("static const uint64_t RAM_RC[%d] = {" % NWORDS)
    for i in range(0, NWORDS, 4):
        print("  " + ", ".join("0x%016xULL" % w for w in words[i:i + 4]) + ",")
    print("};")
