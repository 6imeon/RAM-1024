"""Generate csrc/ram_permute_gen.h: fully unrolled RAM permutation, emitted
once as a body that is instantiated for scalar uint64_t and for clang/GCC
vector types (several independent states processed in SIMD lanes).

    python3 tools/gen_permute.py > csrc/ram_permute_gen.h
"""

ROT = (32, 24, 16, 63)
# v3 rho: left-rotation of rows 2-3 (words 16..31) after the column step;
# rho_i = 2*(13*i mod 32) + 1: 16 distinct odd amounts (never byte-aligned).
RHO = (1, 27, 53, 15, 41, 3, 29, 55, 17, 43, 5, 31, 57, 19, 45, 7)


def g(a, b, c, d, pre="v"):
    va, vb, vc, vd = (pre + str(x) for x in (a, b, c, d))
    out = []
    for i, r in enumerate(ROT):
        if i % 2 == 0:
            out.append("%s += %s; %s ^= %s; %s = ROTR(%s, %d);" % (va, vb, vd, va, vd, vd, r))
        else:
            out.append("%s += %s; %s ^= %s; %s = ROTR(%s, %d);" % (vc, vd, vb, vc, vb, vb, r))
    return " ".join(out)


def round_stmts(skip, kofs, pre="v", T="T"):
    L = []
    for c in range(8):  # v3: constants spread diagonally over all rows
        L.append("%s%d ^= k[%d];" % (pre, (c & 3) * 8 + c, kofs + c))
    for c in range(8):
        L.append(g(c, 8 + c, 16 + c, 24 + c, pre))
    for i, k in enumerate(RHO):  # v3: rho, written as a right-rotation
        L.append("%s%d = ROTR(%s%d, %d);" % (pre, 16 + i, pre, 16 + i, 64 - k))
    for c in range(8):
        L.append(g(c, 8 + (c + 1) % 8, 16 + (c + 2) % 8, 24 + (c + 3) % 8, pre))
    rows = [i for i in range(4) if i != skip]
    for c in range(8):
        x = rows[0] * 8 + c
        y = rows[1] * 8 + (c + 3) % 8
        z = rows[2] * 8 + (c + 5) % 8
        L.append(("{ %s X = P%d, Y = P%d, Z = P%d; P%d = X ^ (~Y & Z); "
                  "P%d = Y ^ (~Z & X); P%d = Z ^ (~X & Y); }"
                  % (T, x, y, z, x, y, z)).replace("P", pre))
    return L


def round_body(skip, kofs):
    return "\n".join("        " + l for l in round_stmts(skip, kofs))


def main_metal():
    """Metal compute kernel: one GPU thread hashes one full 16 KiB leaf."""
    L = []
    a = L.append
    a("#include <metal_stdlib>")
    a("using namespace metal;")
    a("#define ROTR(x, n) rotate((x), (ulong)(64 - (n)))")
    a("kernel void ram_leaf(device const ulong *msg [[buffer(0)]],")
    a("                     device ulong *cvs [[buffer(1)]],")
    a("                     constant ulong *RAM_RC [[buffer(2)]],")
    a("                     constant ulong *prm [[buffer(3)]],")
    a("                     uint gid [[thread_position_in_grid]])")
    a("{")
    a("    /* prm: [0] first node index, [1] IV word 31, [2] #leaves, [3] rounds */")
    a("    if (gid >= prm[2]) return;")
    a("    ulong " + ", ".join("v%d = 0" % i for i in range(32)) + ";")
    a("    v31 = prm[1]; v30 = 128; v28 = prm[0] + gid;")
    a("    int rounds = (int)prm[3];")
    a("    device const ulong *m = msg + (ulong)gid * 2048;")
    a("    for (int b = 0; b <= 128; b++) {")
    a("        if (b < 128) {")
    a("            " + " ".join("v%d ^= m[%d];" % (i, i) for i in range(16)))
    a("            m += 16;")
    a("        } else {")
    a("            v0 ^= 1; v15 ^= 0x8000000000000000UL;")
    a("        }")
    a("        for (int r = 0; r < rounds; r += 4) {")
    a("            constant ulong *k = RAM_RC + 8 * r;")
    for s_ in range(4):
        for st in round_stmts(s_, 8 * s_, "v", "ulong"):
            a("            " + st)
    a("        }")
    a("    }")
    a("    device ulong *o = cvs + (ulong)gid * 16;")
    a("    " + " ".join("o[%d] = v%d;" % (i, i) for i in range(16)))
    a("}")
    print("/* Generated by tools/gen_permute.py --metal -- do not edit. */")
    print("static const char *RAM_METAL_SRC =")
    for line in L:
        print('    "%s\\n"' % line.replace("\\", "\\\\").replace('"', '\\"'))
    print(";")


def main():
    p = print
    p("/* Generated by tools/gen_permute.py -- do not edit. */")
    p("/* Requires: T (word type), ROTR(x,n), LOAD(i) / STORE(i,v) macros. */")
    p("{")
    p("    T " + ", ".join("v%d = LOAD(%d)" % (i, i) for i in range(32)) + ";")
    p("    int r = 0;")
    p("    for (; r + 4 <= rounds; r += 4) {")
    p("        const uint64_t *k = RAM_RC + 8 * r;")
    for s in range(4):
        p(round_body(s, 8 * s))
    p("    }")
    p("    for (; r < rounds; r++) {")
    p("        const uint64_t *k = RAM_RC + 8 * r;")
    p("        switch (r & 3) {")
    for s in range(4):
        p("        case %d: {" % s)
        p(round_body(s, 0))
        p("        } break;")
    p("        }")
    p("    }")
    p("    " + " ".join("STORE(%d, v%d);" % (i, i) for i in range(32)))
    p("}")


if __name__ == "__main__":
    import sys
    if "--metal" in sys.argv:
        main_metal()
    else:
        main()
